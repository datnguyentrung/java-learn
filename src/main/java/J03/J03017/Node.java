package J03.J03017;

public class Node {
    int n, stt;

    public Node(int n, int stt) {
        this.n = n;
        this.stt = stt;
    }

    public int getN() {
        return n;
    }

    public void setN(int n) {
        this.n = n;
    }

    public int getStt() {
        return stt;
    }

    public void setStt(int stt) {
        this.stt = stt;
    }
}
